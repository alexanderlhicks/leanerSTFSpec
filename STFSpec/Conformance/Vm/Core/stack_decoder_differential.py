class FrameError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise FrameError(message)


def pairs(items):
    result = {}
    for key, value in items:
        require(key not in result, 'duplicate JSON key: ' + key)
        result[key] = value
    return result


def bad_constant(value):
    raise FrameError('nonfinite JSON constant: ' + value)


def natural(value):
    require(type(value) is int and value >= 0, 'expected actual nonnegative int')
    return value


def parse_frames(text):
    require(type(text) is str, 'expected text')
    require(text.endswith('\n'), 'missing terminal newline')
    lines = text.split('\n')
    require(lines[-1] == '', 'terminal framing')
    lines.pop()
    require(len(lines) == 512, 'expected exactly 512 rows')
    rows = []
    for index, line in enumerate(lines):
        require(bool(line) and '\r' not in line, 'empty or noncanonical line')
        row = json.loads(line, object_pairs_hook=pairs, parse_constant=bad_constant)
        require(type(row) is dict, 'row must be object')
        require(set(row) == {'kind', 'case', 'op', 'byte', 'result'}, 'row field set')
        require(row['kind'] == 'stack-decoder', 'wrong kind')
        require(natural(row['case']) == index, 'wrong case/order')
        op = 'single' if index < 256 else 'pair'
        byte = index if index < 256 else index - 256
        require(row['op'] == op, 'wrong operation/order')
        require(natural(row['byte']) == byte, 'wrong byte/order')
        result = row['result']
        require(type(result) is dict, 'result must be object')
        require(type(result.get('tag')) is str, 'result tag type')
        if result['tag'] == 'error':
            require(set(result) == {'tag', 'error'}, 'error field set')
            require(result['error'] == 'invalidParameter', 'wrong nominal error')
        else:
            require(result['tag'] == 'ok', 'unknown result tag')
            require(set(result) == {'tag', 'value'}, 'success field set')
            if op == 'single':
                natural(result['value'])
            else:
                value = result['value']
                require(type(value) is list and len(value) == 2, 'pair arity/type')
                natural(value[0])
                natural(value[1])
        rows.append(row)
    return rows


def compare_frames(actual_text, expected_text):
    actual = parse_frames(actual_text)
    expected = parse_frames(expected_text)
    require(actual == expected, 'complete decoder frame mismatch')
    return actual


