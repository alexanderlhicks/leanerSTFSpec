class FrameError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise FrameError(message)


def pairs(items):
    out = {}
    for key, value in items:
        require(key not in out, "duplicate field")
        out[key] = value
    return out


def bad_constant(value):
    raise FrameError("nonfinite JSON: " + value)


def natural(value):
    require(type(value) is int and value >= 0, "invalid natural")


def word(value):
    natural(value)
    require(value < 2**256, "out-of-range word")


def words(value):
    require(type(value) is list and len(value) <= 1024, "invalid bounded model")
    for item in value:
        word(item)


def parse_frames(text):
    require(type(text) is str and bool(text), "empty stream")
    result = []
    for i, line in enumerate(text.splitlines()):
        require(bool(line.strip()), "blank frame")
        try:
            frame = json.loads(line, object_pairs_hook=pairs, parse_constant=bad_constant)
        except (ValueError, TypeError) as error:
            raise FrameError(str(error)) from error
        require(type(frame) is dict and set(frame) == {"kind", "case", "value"}, "frame fields")
        natural(frame["case"])
        require(frame["case"] == i, "frame order")
        require(type(frame["kind"]) is str and frame["kind"] == "stack", "frame kind")
        v = frame["value"]
        require(
            type(v) is dict
            and set(v) == {"label", "op", "input", "arg", "status", "word", "model", "size"},
            "result fields",
        )
        require(type(v["label"]) is str and bool(v["label"]), "label")
        require(type(v["op"]) is str and v["op"] in {"pop", "push", "peek"}, "operation")
        words(v["input"])
        words(v["model"])
        natural(v["size"])
        require(v["size"] == len(v["model"]), "model size")
        require(type(v["status"]) is str, "status type")
        if v["op"] == "pop":
            require(v["arg"] is None, "pop argument")
            require(v["status"] in {"ok", "stackUnderflow"}, "pop status")
        elif v["op"] == "push":
            word(v["arg"])
            require(v["status"] in {"ok", "stackOverflow"}, "push status")
        else:
            natural(v["arg"])
            require(v["status"] in {"some", "none"}, "peek status")
        if (v["op"] == "pop" and v["status"] == "ok") or v["status"] == "some":
            word(v["word"])
        else:
            require(v["word"] is None, "unexpected word")
        result.append(frame)
    return result


def expected_frames():
    return [{"kind": "stack", "case": i, "value": r} for i, r in enumerate(CATALOG)]


def compare_frames(text):
    actual = parse_frames(text)
    require(actual == expected_frames(), "complete frozen frames disagree")
    return actual


