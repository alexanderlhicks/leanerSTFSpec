"""Generate full-byte interpreted guards from the single frozen catalog owner."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "STFSpec/Conformance/Precompiles/kzg-versioned-hash-cases.json"
TARGET = ROOT / "STFSpec/Conformance/Precompiles/KzgVersionedHashGuards.lean"


def generate():
    all_cases = json.loads(CATALOG.read_bytes())["cases"]
    cases = all_cases[:20] + all_cases[905:]
    parts = ["""/-
Copyright (c) 2026 The STFspec Contributors. Licensed under Apache-2.0 OR MIT.
-/

import STFSpec.Precompiles

/-!
# Complete frozen KZG versioned-hash controls

Generated by scripts/gen_kzg_versioned_hash_guards.py; edit the canonical JSON catalog.
Library `EthConformance`. These 41 anchor rows are the catalog's first 20 cases, the
12 boundary and zero cases 905–916 (including two searched suffix-zero cases) and its
nine own supplements 917–925. The first 917 catalog
rows were frozen before the target was implemented; the nine supplements use host
mathematics after the initial helper build. The heartbeat budget below covers the
largest literal inputs.
Spec guidance: STFSpec/informal/modules/EthPrecompiles.md §§3/4/7.
-/

open STFSpec.Precompiles.Kzg
set_option maxRecDepth 4096
set_option maxHeartbeats 8000000
"""]
    def numbers(values):
        return ",\n    ".join(", ".join("0x%02x" % x for x in values[i:i + 12])
                            for i in range(0, len(values), 12))
    for row in cases:
        data = bytes.fromhex(row["hex"])
        result = bytes.fromhex(row["versioned_hash"])
        parts.append("\n-- " + row["id"] + ": " + row["case"] + "\n")
        parts.append("#guard (commitmentToVersionedHash (ByteArray.mk #[" +
                     ("\n    " + numbers(data) if data else "") + "])).toBytes.toList =\n  [" + numbers(result) + "]\n")
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not TARGET.is_file() or TARGET.read_bytes() != expected.encode():
            raise SystemExit("stale KZG versioned-hash guards")
    else:
        TARGET.write_bytes(expected.encode())
    print("PASS KZG guard generation: 41 literal anchors; "
          "926 interpreted/native observations checked separately")


if __name__ == "__main__":
    main()
